#!/usr/bin/env python3
"""Builds source/speedlist.inc from the Darkelf2024 PS2 playable lists for AetherSX2/NetherSX2
(https://github.com/Darkelf2024/PS2-Playable-Lists-for-AetherSX2-NetherSX2, CC BY 4.0), copied in data/.
Changes made: only the EE cycle rate, EE cycle skip and hardware-download columns are used; titles are
reduced to lower-case letters and digits for matching; where both lists name a game, the NetherSX2 list wins.
AetherSX2 scales: cycle rate -3..+3 (-1 = 75%, -2 = 60%, -3 = 50%), cycle skip -1..-3 = Mild..Maximum."""
import re, sys
from pathlib import Path
root = Path(__file__).resolve().parents[1]
def key(title):
    t = title.lower().replace('&', 'and')
    t = re.sub(r'\(.*?\)', '', t)
    return re.sub(r'[^a-z0-9]', '', t)
def num(v):
    v = v.strip()
    m = re.match(r'^([+-]?\d)', v)
    return int(m.group(1)) if m else 0
HW = {'accurate': 'Accurate', 'unsynchronized': 'Unsynchronized', 'disabled readbacks': 'Disable Readbacks', 'disabled': 'Disabled'}
entries = {}
for fname, cols in (('Mangmi_Air_X_PS2_Full_List_2026.md', (1, 2, 3, None)), ('NetherSX2_Game_List_A-Z.md', (1, 2, 3, 8))):
    for line in (root / 'data' / fname).read_text().splitlines():
        if not line.startswith('| ') or line.startswith('| Game') or ':---' in line: continue
        c = [x.strip() for x in line.split('|')]
        if len(c) < 5: continue
        title = c[cols[0]]; k = key(title)
        if not k: continue
        rate = num(c[cols[1]]); skip = -num(c[cols[2]]) if num(c[cols[2]]) < 0 else 0
        hw = HW.get(c[cols[3]].lower(), '') if cols[3] is not None and cols[3] < len(c) else ''
        entries[k] = (title, max(-3, min(3, rate)), max(0, min(3, skip)), hw)  # later file (NetherSX2) wins
out = ['// Generated by tools/make_speedlist.py from data/*.md -- do not edit.',
       '// Source: Darkelf2024, "PS2 Playable Lists for AetherSX2 & NetherSX2",',
       '// https://github.com/Darkelf2024/PS2-Playable-Lists-for-AetherSX2-NetherSX2 , licensed CC BY 4.0',
       '// (https://creativecommons.org/licenses/by/4.0/). Changes: only EE cycle rate/skip and hardware',
       '// download kept; titles normalised for matching.',
       '// {normalised title, EE cycle rate (-3..3, AetherSX2 scale), EE cycle skip (0..3), hardware download}']
for k in sorted(entries):
    t, r, s, h = entries[k]
    out.append('{"%s", %d, %d, "%s"},  // %s' % (k, r, s, h, t.replace('*/', '')))
(root / 'source' / 'speedlist.inc').write_text('\n'.join(out) + '\n')
print(len(entries), 'games')
